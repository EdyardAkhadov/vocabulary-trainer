type DeepWiden<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepWiden<T[K]>;
};

export type TranslationDictionary = DeepWiden<(typeof baseTranslations)['en']>;
export type FullTranslationDictionary = TranslationDictionary & VocabularyTranslation;

const coreTranslations = {
  ...baseTranslations,
  ...extraTranslations,
} satisfies Record<AppLanguage, TranslationDictionary>;

export const translations = Object.fromEntries(
  (Object.keys(coreTranslations) as AppLanguage[]).map((language) => [
    language,
    {
      ...coreTranslations[language],
      ...vocabularyTranslations[language],
    },
  ]),
) as Record<AppLanguage, FullTranslationDictionary>;
